// Writes locales.go from Node's CLDR data, so the companion and Alibi agree:
// - for every two-letter country code, the locale Alibi derives when GeoJS places the connection
//   there (js/sites.js, ipCover);
// - country names, for the tray and its alerts;
// - each time zone's country, so the agent knows which country is home.
// Run `go generate` in companion/ after a Node update brings new CLDR data.
import { writeFileSync } from 'node:fs'

const letters = [...'ABCDEFGHIJKLMNOPQRSTUVWXYZ']
const codes = letters.flatMap((a) => letters.map((b) => a + b))
const names = new Intl.DisplayNames(['en'], { type: 'region', fallback: 'none' })

const rows = (entries, perRow) => {
  const out = []
  for (let i = 0; i < entries.length; i += perRow) out.push(`\t${entries.slice(i, i + perRow).join(', ')},`)
  return out.join('\n')
}

const locales = codes.map((code) => {
  const { language, region } = new Intl.Locale(`und-${code}`).maximize()
  return `"${code}": "${language}-${region}"`
})
// Only real countries have names; the codes CLDR reserves (AA, QM..QZ, XA..XZ, ZZ) don't.
const countries = codes.filter((code) => names.of(code) && !/^(AA|Q[M-Z]|X[A-Z]|ZZ|EU|EZ|UN)$/.test(code))
const countryNames = countries.map((code) => `"${code}": ${JSON.stringify(names.of(code))}`)
const zones = new Map()
for (const code of countries) {
  for (const zone of new Intl.Locale(`und-${code}`).getTimeZones?.() ?? []) if (!zones.has(zone)) zones.set(zone, code)
}
// CLDR, and so Windows and Chrome, still use a zone's old name where it was renamed. GeoJS uses the new one.
const renamed = {
  'Asia/Calcutta': 'Asia/Kolkata', 'Europe/Kiev': 'Europe/Kyiv', 'Asia/Katmandu': 'Asia/Kathmandu', 'Asia/Rangoon': 'Asia/Yangon',
  'America/Godthab': 'America/Nuuk', 'Asia/Saigon': 'Asia/Ho_Chi_Minh', 'Atlantic/Faeroe': 'Atlantic/Faroe', 'Pacific/Enderbury': 'Pacific/Kanton',
}
for (const [old, now] of Object.entries(renamed)) if (zones.has(old) && !zones.has(now)) zones.set(now, zones.get(old))
const zoneCountries = [...zones].sort(([a], [b]) => a.localeCompare(b)).map(([zone, code]) => `"${zone}": "${code}"`)

writeFileSync(
  new URL('locales.go', import.meta.url),
  `// Code generated by gen_locales.mjs with Node ${process.version} (CLDR ${process.versions.cldr}). DO NOT EDIT.

package main

// countryLocales holds, for every two-letter country code, the locale Alibi gives a connection
// placed there: the country's most likely language, from CLDR.
var countryLocales = map[string]string{
${rows(locales, 6)}
}

// countryNames holds each country's name in English.
var countryNames = map[string]string{
${rows(countryNames, 4)}
}

// zoneCountries holds the country of each time zone.
var zoneCountries = map[string]string{
${rows(zoneCountries, 3)}
}
`,
)
